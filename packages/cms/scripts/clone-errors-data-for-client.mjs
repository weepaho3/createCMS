// Duplicates `src/errors-data.ts` into `src/client/errors-data.generated.ts`.
// bunchee shares a module imported by both the server entry and a `'use client'`
// entry; the shared chunk inherits `'use client'`, Next.js stubs it on the
// server, and CMSError throws TypeError on `def.status`. Two files means two
// chunks. Do not import the generated clone from server code.
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'src/errors-data.ts');
const destPath = path.join(root, 'src/client/errors-data.generated.ts');

const source = fs.readFileSync(sourcePath, 'utf8');
const body = source.replace(/^\/\*\*[\s\S]*?\*\/\n/, '');
const out = `/**
 * Generated by scripts/clone-errors-data-for-client.mjs from
 * src/errors-data.ts. The client bundle needs its own module so bunchee
 * cannot put CMS_ERRORS in a shared use-client chunk.
 */
${body}`;

fs.writeFileSync(destPath, out);
